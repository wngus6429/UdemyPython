t = (1,2,3,4,5)
t2 = (5,6,7,8,9)
r=[]
for i in t:
    if i % 2 == 0:
        r.append(i)    
print(r)

# 를 간결하게
# 처리가 좀 빠르다는 장점이있음
r = [i for i in t if i % 2 == 0]
print(r)

r = []
for i in t:
    for j in t2:
        r.append(i * j) 
# [5, 6, 7, 8, 9, 10, 12, 14, 16, 18, 15, 18, 21, 24, 27, 20, 24, 28, 32, 36, 25, 30, 35, 40, 45]
print(r)
# 를 한줄로
r = [i * j for i in t for j in t2]
# [5, 6, 7, 8, 9, 10, 12, 14, 16, 18, 15, 18, 21, 24, 27, 20, 24, 28, 32, 36, 25, 30, 35, 40, 45]
print(r)